const diagram = defineTopic('g6-diagram', 'ダイヤグラム', [
    (r) => {
        const [p, f] = r.pickN(names, 2);
        const v = until(r, () => {
            const a = r.pick([60, 75, 80]);
            const k = r.pick([2, 3]); // 妹の速さは兄の何倍か
            const t1 = k * 2 * r.int(2, 5);
            const s = 2 * r.int(2, 5);
            const rest = r.int(2, 6) * 5;
            return { a, k, c: a * k, t1, s, rest, dist: a * t1, pass: (k * s) / (k - 1), end: 2 * t1 + rest };
        }, x => Number.isInteger(x.pass) && x.pass < x.t1 - 1 && x.s + x.t1 / x.k < x.t1);
        const arrive = v.s + v.t1 / v.k; // 妹が図書館に着く時間
        const leave = v.end - v.t1 / v.k; // 妹が図書館を出る時間
        return {
            text: [
                `${p}さんと妹の${f}さんは、同じ日に、家から図書館へ出かけました。家から図書館までは、まっすぐな1本道です。下のグラフは、${p}さんが家を出発してからの時間（分）と、家からの道のり（m）の関係を、2人それぞれについて表したものです。グラフの実線が${p}さん、点線が${f}さんのようすを表しています。`,
                `${p}さんは、歩いて家を出発し、一定の速さで図書館まで行きました。図書館に着くと、そこで${v.rest}分間、本を読んだりかりたりしてすごしました。そのあと、行きと同じ速さで歩いて、同じ道を通って家に帰りました。`,
                `${f}さんは、${p}さんが家を出発してから${v.s}分後に、自転車に乗って家を出発しました。${f}さんの自転車の速さは一定で、${p}さんの歩く速さのちょうど${v.k}倍です。${f}さんは、図書館へ向かうとちゅうで、前を歩いている${p}さんを追いこして、先に図書館に着きました。`,
                `${f}さんは、図書館でしばらくすごしたあと、行きと同じ速さで、自転車に乗って同じ道を通って家に帰りました。${f}さんは、帰り道では${p}さんを追いこすことはなく、${p}さんとちょうど同じ時こくに家に着きました。`,
                `グラフのたてのじくの目もりは、家から図書館までの道のりを表しています。また、横のじくの目もりのうち、アとイにあてはまる数は、グラフには書かれていません。`,
                '2人とも、歩いている間や自転車に乗っている間は、とちゅうで止まったり、速さを変えたりすることはありませんでした。',
            ],
            figure: graph({
                xLabel: '時間（分）', yLabel: '道のり（m）', xMax: v.end * 1.05, yMax: v.dist * 1.1,
                xTicks: [{ v: 0, text: '0' }, { v: v.s, text: `${v.s}` }, { v: v.t1, text: `${v.t1}` }, { v: v.t1 + v.rest, text: 'ア' }, { v: v.end, text: 'イ' }],
                yTicks: [{ v: v.dist, text: `${v.dist}` }],
                lines: [
                    { points: [[0, 0], [v.t1, v.dist], [v.t1 + v.rest, v.dist], [v.end, 0]] },
                    { points: [[v.s, 0], [arrive, v.dist], [leave, v.dist], [v.end, 0]], dashed: true },
                ],
            }),
            questions: [
                q(`${p}さんの歩く速さは、分速何mですか。`, v.a, 'm', [v.c, v.dist / (v.t1 + v.rest), v.dist / v.end], { prefix: '分速', step: 5 }),
                q(`${f}さんが${p}さんを追いこしたのは、${p}さんが家を出発してから何分後ですか。`, v.pass, '分後', [v.pass - v.s, v.s + v.t1 / v.k, v.s * v.k]),
                q(`${f}さんが図書館を出発したのは、${p}さんが家を出発してから何分後ですか。`, leave, '分後', [v.t1 + v.rest, v.end, leave - v.s]),
            ],
        };
    },
]);

const hayasaHi = defineTopic('g6-hayasa-hi', '速さと比', [
    (r) => {
        const [p, f] = r.pickN(names, 2);
        // [兄の速さの比, 弟の速さの比, 兄がBに着くまでの時間（比の和の倍数）]
        const [a, b, time] = r.pick([[5, 3, 16], [5, 3, 24], [3, 2, 10], [3, 2, 15], [3, 2, 20], [4, 3, 14], [4, 3, 21], [7, 5, 12], [7, 5, 24], [5, 4, 18]]);
        const s = r.pick([10, 15, 20]);
        const dist = a * s * time;
        const gap = s * time * (a - b);
        const back = (gap * a) / (a + b);
        const meet = (2 * a * time) / (a + b);
        return {
            text: [
                `${p}さんと弟の${f}さんは、休みの日に、川ぞいのサイクリングロードで、歩く練習をすることにしました。サイクリングロードには、スタート地点のA地点と、折り返し地点のB地点があり、その間はまっすぐな1本道になっています。`,
                `2人は、A地点を同時に出発して、B地点に向かって歩き始めました。2人の歩く速さはそれぞれ一定で、${p}さんの速さと${f}さんの速さの比は、${a}:${b}です。${p}さんの歩く速さは、分速${a * s}mです。`,
                `同じ時間だけ歩くとき、進む道のりの比は、速さの比と同じになります。ですから、2人が同時に出発したあと、${p}さんが進んだ道のりと${f}さんが進んだ道のりの比も、いつも${a}:${b}になっています。`,
                `先にB地点に着いたのは、速く歩いている${p}さんでした。${p}さんがB地点に着いたとき、${f}さんは、まだB地点の${gap}m手前のところを歩いていました。`,
                `${p}さんは、B地点に着くとすぐに向きを変えて、それまでと同じ速さで、A地点に向かって引き返しました。${f}さんは、そのままB地点に向かって歩き続けました。そして、2人は、A地点とB地点の間のとちゅうで出会いました。向かい合って進む2人が出会うまでに進む道のりの比も、速さの比と同じになります。`,
                '2人とも、とちゅうで休んだり、速さを変えたりすることはありませんでした。また、サイクリングロードは平らで、上り坂や下り坂はないものとします。',
            ],
            questions: [
                q('A地点からB地点までの道のりは何mですか。', dist, 'm', [gap * a, (gap * b) / (a - b), dist + gap], { step: 100 }),
                q('2人が出会った地点は、B地点から何mはなれたところですか。', back, 'm', [gap - back, gap / 2, gap], { step: 10 }),
                q('2人が出会ったのは、A地点を出発してから何分後ですか。', meet, '分後', [time, time + gap / (a * s), meet + 2]),
            ],
        };
    },
]);

const ike = defineTopic('g6-ike', '池のまわりの旅人算', [
    (r) => {
        const [a, b, c] = r.pickN(names, 3);
        const v = until(r, () => {
            const [va, vb, vc] = [r.int(14, 20) * 5, r.int(9, 13) * 5, r.int(8, 24) * 5];
            const len = r.int(8, 30) * 100;
            return { va, vb, vc, len, t1: len / (va + vb), t2: len / (va - vb), t3: len / (va + vc) };
        }, x => [x.t1, x.t2, x.t3].every(Number.isInteger) && x.t2 <= 120 && x.vc !== x.vb && x.vc < x.va && x.t3 !== x.t1);
        return {
            text: [
                `大きな公園のまん中に池があり、そのまわりを、ぐるりと1しゅうする遊歩道がつくられています。${a}さん、${b}さん、${c}さんの3人は、この遊歩道を歩いて、いろいろなことを調べてみました。3人の歩く速さはそれぞれ一定ですが、3人ともちがう速さです。3人の中では、${a}さんの歩く速さがいちばん速く、分速${v.va}mです。`,
                `【1回目】${a}さんと${b}さんが、遊歩道の同じ地点から、同時に、たがいに反対の向きに歩き始めました。すると、2人は、歩き始めてからちょうど${v.t1}分後に、はじめて出会いました。反対の向きに歩く2人がはじめて出会うまでに、2人が歩いた道のりの合計は、遊歩道のちょうど1しゅう分になります。`,
                `【2回目】${a}さんと${b}さんが、遊歩道の同じ地点から、同時に、こんどは同じ向きに歩き始めました。すると、速く歩く${a}さんが、${b}さんよりも遊歩道をちょうど1しゅう分だけ多く歩いて、歩き始めてからちょうど${v.t2}分後に、はじめて${b}さんに後ろから追いつきました。`,
                `【3回目】${a}さんと${c}さんが、遊歩道の同じ地点から、同時に、たがいに反対の向きに歩き始めました。すると、2人は、歩き始めてからちょうど${v.t3}分後に、はじめて出会いました。`,
                '同じ向きに歩く場合、2人の間のきょりは、1分間に、2人の速さの差の分だけ広がっていきます。反対の向きに歩く場合は、1分間に、2人の速さの和の分だけ、2人は近づいていきます。',
            ],
            figure: shape(10, 8, {
                circles: [{ cx: 5, cy: 4, r: 3.4 }, { cx: 5, cy: 4, r: 2.4, fill: 'water' }],
                labels: [{ at: [5, 4], text: '池' }, { at: [5, 0.1], text: '出発する地点' }],
                points: [{ at: [5, 0.6], text: '' }],
            }, 'circle'),
            questions: [
                q(`${b}さんの歩く速さは、分速何mですか。`, v.vb, 'm', [v.va - v.vb, v.len / v.t1, v.vb + 10], { prefix: '分速', step: 5 }),
                q('遊歩道1しゅうの長さは何mですか。', v.len, 'm', [v.va * v.t1, v.va * v.t2, v.len + 200], { step: 100 }),
                q(`${c}さんの歩く速さは、分速何mですか。`, v.vc, 'm', [v.len / v.t3, v.vc + 10, v.va - v.vc], { prefix: '分速', step: 5 }),
            ],
        };
    },
]);

const koshou = defineTopic('g6-ryuusui', '流水算（エンジンの故障）', [
    (r) => {
        // [静水での速さ, 流れの速さ, 町の間の道のり, 故障で流された時間（分）]
        const [s, c, d, m] = r.pick([
            [15, 3, 36, 20], [15, 3, 36, 40], [10, 2, 24, 20], [10, 2, 24, 40], [12, 4, 32, 20], [12, 4, 32, 30],
            [9, 3, 24, 20], [9, 3, 24, 30], [20, 4, 48, 20], [14, 2, 48, 30],
        ]);
        const [down, up] = [d / (s + c), d / (s - c)];
        const lost = m + (c * m) / (s - c);
        const drift = (c * m) / 60;
        const kmText = Number.isInteger(drift) ? `${drift}` : `${Math.round(drift * 10) / 10}`;
        return {
            text: [
                `ある大きな川の下流にP町、上流にQ町があり、2つの町は川にそって${d}kmはなれています。この2つの町の間を、1せきの定期船が、毎日行き来しています。`,
                `この定期船は、流れのない水の上では、いつも一定の速さで進みます。川の水は、上流のQ町から下流のP町に向かって、いつも一定の速さで流れています。船が川を下るときには、船の速さに川の流れの速さが加わり、川を上るときには、船の速さから川の流れの速さがひかれます。`,
                `ふだん、この定期船は、Q町からP町まで下るのに、ちょうど${down}時間かかります。また、P町からQ町まで上るのに、ちょうど${up}時間かかります。`,
                `ある日、定期船がP町を出発してQ町に向かって川を上っているとちゅうで、とつぜんエンジンが止まってしまいました。エンジンが止まっている間、船は、川の流れと同じ速さで、下流に向かって流されました。船長さんたちが急いで修理をしたところ、エンジンは、止まってからちょうど${m}分後にふたたび動き出しました。船は、そのあとは、ふだんと同じ速さで川を上って、Q町に着きました。`,
                `この日、船がエンジンの止まっている間に下流へ流された道のりは、およそ${kmText}kmでした。船は、流された分だけ、もう一度川を上り直さなければなりませんでした。`,
                'エンジンが止まっていた時間のほかに、流された道のりを上り直すための時間も、ふだんより多くかかることになります。',
            ],
            questions: [
                q('この定期船の、流れのない水の上での速さは、時速何kmですか。', s, 'km', [s + c, s - c, d / down / 2], { prefix: '時速' }),
                q('この川の流れの速さは、時速何kmですか。', c, 'km', [s - c - c > 0 ? s - 2 * c : c + 3, (s + c) / 2, c * 2], { prefix: '時速' }),
                q('エンジンが止まった日、定期船がP町を出発してからQ町に着くまでにかかった時間は、何時間何分ですか。', up * 60 + lost, '', [up * 60 + m, up * 60, up * 60 + lost + m], { format: hourMin, step: 5 }),
            ],
        };
    },
]);

const surechigai = defineTopic('g6-tsuuka', '通過算（すれちがいと追いこし）', [
    (r) => {
        const p = r.pick(names);
        const v = until(r, () => {
            const [v2, v1] = r.pick([[30, 20], [25, 15], [35, 15], [30, 15], [25, 20], [35, 25]]);
            const t0 = r.int(6, 9);
            const sum = (v1 + v2) * r.int(6, 12);
            return { v1, v2, t0, len2: v2 * t0, len1: sum - v2 * t0, pass: sum / (v1 + v2), over: sum / (v2 - v1) };
        }, x => x.len1 >= 100 && x.len1 <= 260 && Number.isInteger(x.over) && x.len1 !== x.len2);
        return {
            text: [
                `鉄道がすきな${p}さんは、休みの日に、家の近くの駅のホームで、通りすぎる列車を観察しました。この駅を通る線路は、上りと下りの2本がならんでいて、特急列車と普通列車が走っています。この問題では、どの列車も、観察している間は一定の速さで走っているものとします。`,
                `はじめに、長さ${v.len2}mの特急列車が、駅に止まらずに通りすぎていきました。${p}さんがストップウォッチではかったところ、特急列車の先頭が自分の目の前に来てから、いちばん後ろが目の前を通りすぎるまでに、ちょうど${v.t0}秒かかりました。立っている人の前を列車が通りすぎるとき、列車は、その間に、列車自身の長さと同じ道のりだけ進んでいます。`,
                `次に、この特急列車は、となりの線路を反対の向きに走ってくる、長さ${v.len1}mの普通列車とすれちがいました。2つの列車の先頭どうしが出会ってから、いちばん後ろどうしがはなれるまでに、ちょうど${v.pass}秒かかりました。反対の向きに走る2つの列車がすれちがうとき、その間に2つの列車が進む道のりの合計は、2つの列車の長さの合計と同じになります。`,
                `${p}さんは、「もし、この特急列車と普通列車が、ならんだ線路を同じ向きに走っていたら、特急列車が普通列車を追いこすのに、どれくらいの時間がかかるのだろう」と考えました。追いこしにかかる時間とは、特急列車の先頭が普通列車のいちばん後ろに追いついてから、特急列車のいちばん後ろが普通列車の先頭を完全にぬきさるまでの時間のことです。`,
            ],
            questions: [
                q('特急列車の速さは、秒速何mですか。', v.v2, 'm', [v.len2 / v.pass, v.v1 + v.v2, v.v2 + 5], { prefix: '秒速', step: 5 }),
                q('普通列車の速さは、秒速何mですか。', v.v1, 'm', [v.v1 + v.v2, v.len1 / v.pass, v.v2 - v.v1], { prefix: '秒速', step: 5 }),
                q('特急列車と普通列車が同じ向きに走っているとすると、特急列車が普通列車を追いこすのに何秒かかりますか。', v.over, '秒', [v.pass, v.len1 / (v.v2 - v.v1), (v.len1 + v.len2) / v.v2]),
            ],
        };
    },
]);

export default [...diagram, ...hayasaHi, ...ike, ...koshou, ...surechigai];
