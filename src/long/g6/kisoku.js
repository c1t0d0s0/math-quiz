const suuhyou = defineTopic('g6-suuhyou', '数表のきまり', [
    (r) => {
        const p = r.pick(names);
        const first = n => (n * (n - 1)) / 2 + 1;
        const [n1, n2] = [r.int(8, 15), r.int(9, 16)];
        const n3 = r.int(12, 22);
        const target = first(n3) + r.int(1, n3 - 2);
        const rowSum = (n2 * (first(n2) + first(n2) + n2 - 1)) / 2;
        const row = n => Array.from({ length: n }, (_, i) => first(n) + i).join('　');
        return {
            text: [
                `${p}さんは、1から順に、整数を下の表のようにならべていきました。表のいちばん上の行を1だん目、その下の行を2だん目、さらにその下の行を3だん目、…とよぶことにします。`,
                `1だん目には、「1」の1個だけをならべます。2だん目には、その続きの「2、3」の2個を、左から順にならべます。3だん目には、さらにその続きの「4、5、6」の3個をならべます。このように、どのだんにも、だんの番号と同じ個数の整数を、前のだんの続きから、左から小さい順にならべていきます。表には、5だん目までが書かれていますが、${p}さんは、このきまりにしたがって、そのあとも、ずっと下のだんまで数をならべ続けました。`,
                `このような表では、それぞれのだんの「左はしの数」や「右はしの数」に注目すると、きまりを見つけやすくなります。たとえば、3だん目の右はしの数は6ですが、これは、1だん目から3だん目までにならんでいる数の個数の合計、つまり1+2+3と同じです。同じように考えると、あるだんの右はしの数は、1からそのだんの番号までの整数を全部たした数になっています。また、あるだんの左はしの数は、その1つ上のだんの右はしの数よりも1だけ大きい数です。`,
                `1から順にならんだ整数の和は、「（はじめの数＋おわりの数）×個数÷2」という式でもとめることができます。この式は、あるだんにならんでいる数を全部たすときにも、同じように使うことができます。`,
            ],
            figure: table(['だん', 'ならんでいる数'], [1, 2, 3, 4, 5].map(n => [`${n}だん目`, row(n)])),
            questions: [
                q(`${n1}だん目の左はしの数はいくつですか。`, first(n1), '', [first(n1) - 1, first(n1 + 1), (n1 * (n1 + 1)) / 2 + 1]),
                q(`${n2}だん目にならんでいる数を全部たすと、いくつになりますか。`, rowSum, '', [first(n2) * n2, rowSum + n2, rowSum - n2], { step: Math.max(1, Math.round(n2 / 2)) }),
                q(`${target}という数は、何だん目にありますか。`, n3, 'だん目', [n3 + 1, n3 - 1, target - first(n3) + 1]),
            ],
        };
    },
]);

// たて rows・横 cols に区切られた道を、右か上にだけ進む道順の数
function paths(cols, rows) {
    let n = 1;
    for (let i = 1; i <= rows; i++) n = (n * (cols + i)) / i;
    return Math.round(n);
}

const michijun = defineTopic('g6-michijun', '道順の数', [
    (r) => {
        const p = r.pick(names);
        const v = until(r, () => {
            const [cols, rows] = [r.int(3, 5), r.int(3, 4)];
            return { cols, rows, px: r.int(1, cols - 1), py: r.int(1, rows - 1) };
        }, () => true);
        const all = paths(v.cols, v.rows);
        const via = paths(v.px, v.py) * paths(v.cols - v.px, v.rows - v.py);
        const lines = [];
        for (let i = 0; i <= v.cols; i++) lines.push({ from: [i, 0], to: [i, v.rows] });
        for (let j = 0; j <= v.rows; j++) lines.push({ from: [0, j], to: [v.cols, j] });
        return {
            text: [
                `${p}さんの住んでいる町は、下の図のように、東西にのびる道と南北にのびる道が、ごばんの目のようにきちんと区切られています。図の線は道を表していて、線と線が交わっているところが交差点です。${p}さんの家は、図の左下のA地点にあります。${p}さんの通っている学校は、図の右上のB地点にあります。図では、上が北、右が東です。`,
                `${p}さんは、毎朝、家から学校まで歩いて通っています。遠回りをすると学校におくれてしまうので、いつも、もっとも短い道のりで学校まで行くことにしています。A地点からB地点までもっとも短い道のりで行くためには、どの交差点でも、「東（右）へ進む」か「北（上）へ進む」かのどちらかだけを選んで進み、西（左）や南（下）へはけっして進まないようにしなければなりません。`,
                `このような道順の数を数えるときには、それぞれの交差点に、「A地点からその交差点まで行く道順が何通りあるか」を書きこんでいく方法がべんりです。ある交差点に行くには、その交差点の1つ西の交差点から東へ進んで来る場合と、1つ南の交差点から北へ進んで来る場合の2つがあります。ですから、ある交差点に書きこむ数は、1つ西の交差点に書いた数と、1つ南の交差点に書いた数をたしたものになります。A地点から真東、または真北に進むだけで行ける交差点への道順は、どれも1通りです。`,
                `図のP地点には、${p}さんの友だちの家があります。${p}さんは、友だちの家の前を通って、いっしょに学校へ行く日もあります。また、ある日、P地点の交差点が道路工事のために通行止めになり、P地点を通ることができなくなりました。`,
            ],
            figure: shape(v.cols, v.rows, {
                lines,
                points: [
                    { at: [0, 0], text: 'A', dx: -12, dy: 16 },
                    { at: [v.cols, v.rows], text: 'B', dx: 12, dy: -6 },
                    { at: [v.px, v.py], text: 'P', dx: 11, dy: -7 },
                ],
            }),
            questions: [
                q('A地点からB地点まで、もっとも短い道のりで行く道順は、全部で何通りありますか。', all, '通り', [(v.cols + 1) * (v.rows + 1), v.cols * v.rows, all + v.cols]),
                q('A地点からP地点を通ってB地点まで、もっとも短い道のりで行く道順は、何通りありますか。', via, '通り', [paths(v.px, v.py) + paths(v.cols - v.px, v.rows - v.py), paths(v.px, v.py), all - via]),
                q('P地点が通行止めの日に、A地点からB地点まで、もっとも短い道のりで行く道順は、何通りありますか。', all - via, '通り', [via, all - paths(v.px, v.py), all - 1]),
            ],
        };
    },
]);

const league = defineTopic('g6-league', '条件の整理（リーグ戦）', [
    (r) => {
        const v = until(r, () => {
            const n = r.int(5, 8);
            const games = (n * (n - 1)) / 2;
            const draws = r.int(2, 6);
            const wins = r.int(2, n - 2);
            return { n, games, draws, wins, points: 3 * wins + (n - 1 - wins) };
        }, x => x.n - 1 - x.wins <= x.draws && x.n - 1 - x.wins >= 1);
        const total = 3 * (v.games - v.draws) + 2 * v.draws;
        return {
            text: [
                `${r.pick(schools)}市では、毎年秋に、市内の小学生サッカーチームによる大会が開かれます。今年の大会には、全部で${v.n}チームが参加しました。大会は、「総当たり戦（リーグ戦）」という方法で行われます。総当たり戦とは、参加しているどのチームも、自分以外のすべてのチームと、ちょうど1回ずつ試合をする方法のことです。`,
                `試合の結果によって、それぞれのチームには、下の表のきまりにしたがって「勝ち点」があたえられます。試合に勝ったチームには勝ち点3、負けたチームには勝ち点0があたえられます。また、試合が引き分けになったときは、試合をした両方のチームに、勝ち点が1ずつあたえられます。すべての試合が終わったときに、勝ち点の合計がいちばん多いチームが優勝です。`,
                `このきまりでは、勝ち負けがついた試合では、2つのチームにあたえられる勝ち点の合計が3になります。これに対して、引き分けの試合では、2つのチームにあたえられる勝ち点の合計は2になります。つまり、引き分けの試合が1つあるごとに、大会全体であたえられる勝ち点の合計は、1ずつ少なくなることになります。`,
                `今年の大会では、すべての試合が終わってみると、引き分けに終わった試合が、全部で${v.draws}試合ありました。優勝したのはAチームで、Aチームは、大会を通じて1回も負けませんでした。Aチームの勝ち点の合計は、${v.points}でした。`,
            ],
            figure: table(['試合の結果', '勝ち', '引き分け', '負け'], [['勝ち点', '3', '1', '0']], '勝ち点のきまり'),
            questions: [
                q('今年の大会で行われた試合は、全部で何試合ですか。', v.games, '試合', [v.n * (v.n - 1), v.n * v.n, v.games - v.n]),
                q('すべての試合が終わったとき、全チームの勝ち点を合計すると、いくつになりますか。', total, '', [3 * v.games, total - v.draws, 3 * v.games - 2 * v.draws]),
                q('優勝したAチームは、何勝しましたか。', v.wins, '勝', [v.n - 1 - v.wins, Math.floor(v.points / 3), v.wins + 1]),
            ],
        };
    },
]);

export default [...suuhyou, ...michijun, ...league];
