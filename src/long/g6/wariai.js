const newton = defineTopic('g6-newton', 'ニュートン算', [
    (r) => {
        const p = r.pick(names);
        // [窓口1つが1分間に通す人数, 1分間に列に加わる人数, はじめの行列, 窓口の数 a・b・c]
        const [y, x, n, a, b, c] = r.pick([
            [10, 20, 240, 3, 4, 6], [10, 20, 120, 3, 4, 6], [6, 12, 72, 3, 4, 5], [6, 12, 144, 3, 4, 5],
            [8, 16, 160, 3, 4, 6], [8, 16, 96, 3, 4, 6], [5, 10, 100, 3, 4, 7], [5, 10, 150, 3, 4, 7], [12, 24, 360, 3, 5, 4],
        ]);
        const time = k => n / (k * y - x);
        return {
            text: [
                `${p}さんは、夏休みに、家族といっしょに人気の遊園地へ出かけました。遊園地の入場口には、開園の時こくよりも前から、たくさんの人がならんで行列を作っていました。開園の時こくになると、係の人が入場口の窓口を開けて、ならんでいる人を、行列の先頭から順番に入場させ始めました。`,
                `開園したあとも、遊園地には次々に人がやって来て、行列のいちばん後ろにならびます。行列に新しく加わる人の数は、1分間あたり、いつも同じ人数だとします。また、入場口の窓口は、どれも同じ速さで仕事をしていて、1つの窓口が1分間に入場させることができる人数は、ちょうど${y}人です。`,
                `遊園地の係の人の記録によると、開園と同時に窓口を${a}つ開けた日は、開園してからちょうど${time(a)}分後に、行列がなくなりました。また、べつの日に、開園と同時に窓口を${b}つ開けたところ、開園してからちょうど${time(b)}分後に、行列がなくなりました。この2つの日は、開園の時こくにならんでいた人数も、1分間に行列に加わる人数も、まったく同じでした。`,
                `行列がなくなるまでの間に窓口から入場した人数の合計は、「開園の時こくにならんでいた人数」と、「行列がなくなるまでの間に新しく行列に加わった人数」をたしたものと同じになります。このことを使うと、わかっていない人数をもとめることができます。`,
                `今日は、とくに来場者が多くなりそうなので、遊園地では、開園と同時に窓口を${c}つ開けることにしました。開園の時こくにならんでいる人数と、1分間に行列に加わる人数は、記録のあった2つの日と同じだとします。`,
            ],
            questions: [
                q('開園したあと、1分間に行列に加わる人数は何人ですか。', x, '人', [y, x + y, x / 2, a * y - x]),
                q('開園の時こくに行列にならんでいた人数は何人ですか。', n, '人', [a * y * time(a), b * y * time(b), x * time(a)], { step: 10 }),
                q(`窓口を${c}つ開けた今日は、開園してから何分後に行列がなくなりますか。`, time(c), '分後', [n / (c * y), time(b) - 1, time(b) / 2]),
            ],
        };
    },
]);

const kyuusui = defineTopic('g6-shigoto', '仕事算（給水と排水）', [
    (r) => {
        const p = r.pick(names);
        // [満水の量, Aの1分間の給水量, Bの1分間の給水量, Cの1分間の排水量]
        const [w, ra, rb, rc] = r.pick([[120, 6, 4, 5], [180, 9, 6, 5], [240, 10, 6, 4], [360, 12, 8, 5], [72, 6, 3, 1], [240, 12, 8, 5], [360, 15, 9, 6]]);
        const m = until(r, () => r.int(4, 30), x => (w - (ra - rc) * x) % (ra + rb) === 0 && w - (ra - rc) * x > 0);
        const rest = (w - (ra - rc) * m) / (ra + rb);
        return {
            text: [
                `${p}さんの通う小学校には、低学年用の小さなプールがあります。このプールには、水を入れるための2本の給水管AとBがあり、また、プールの底には、水をぬくための排水管Cがついています。どの管も、せんを開けている間は、1分間あたりいつも同じ量の水が流れます。ただし、3本の管を流れる水の量は、それぞれちがっています。`,
                `プールがからの状態から、給水管Aだけを開けて水を入れると、ちょうど${w / ra}分で満水になります。同じように、からの状態から給水管Bだけを開けて水を入れると、ちょうど${w / rb}分で満水になります。また、満水の状態から、給水管を2本ともしめて、排水管Cだけを開けると、ちょうど${w / rc}分でプールはからになります。`,
                `このような問題では、プールの満水の量を、それぞれの時間のどれでもわり切れる数で表すと考えやすくなります。たとえば、満水の量を${w}とすると、給水管Aからは1分間に${ra}ずつ水が入ることになります。`,
                `ある日、プールがからの状態から、当番の先生が水を入れ始めました。先生は、給水管AとBの2本を開けるつもりでしたが、まちがえて、給水管Aと排水管Cを開けてしまいました。そのため、水は少しずつしかたまりませんでした。先生は、水を入れ始めてから${m}分後にまちがいに気がつき、すぐに排水管Cをしめて、給水管Bを開けました。そのあとは、給水管AとBの2本で、満水になるまで水を入れ続けました。`,
            ],
            questions: [
                q('プールがからの状態から、給水管AとBの2本を同時に開けて水を入れると、何分で満水になりますか。', w / (ra + rb), '分', [(w / ra + w / rb) / 2, w / ra + w / rb, w / (ra + rb) + 3]),
                q('プールがからの状態から、給水管AとB、排水管Cの3本をすべて同時に開けると、何分で満水になりますか。', w / (ra + rb - rc), '分', [w / (ra + rb + rc), w / (ra + rb) + w / rc, w / (ra + rb) + 2]),
                q('まちがえた日、先生が水を入れ始めてから満水になるまでに、全部で何分かかりましたか。', m + rest, '分', [rest, m + w / (ra + rb), m + rest + 2]),
            ],
        };
    },
]);

const yaritori = defineTopic('g6-noudo', '食塩水のやりとり', [
    (r) => {
        const p = r.pick(names);
        const v = until(r, () => {
            const [a, x] = [r.int(8, 20), r.int(2, 6) * 100];
            const [b, y] = [r.int(2, 9), r.int(2, 6) * 100];
            const z = r.int(1, 3) * 100;
            const saltA = (x * a) / 100;
            const saltB = (y * b) / 100;
            const concB = ((saltB + (z * a) / 100) * 100) / (y + z);
            const finalSalt = saltA - (z * a) / 100 + (z * concB) / 100;
            return { a, x, b, y, z, saltA, saltB, concB, finalSalt, concA: (finalSalt * 100) / x };
        }, s => s.z < s.x && s.a > s.b + 3 && Number.isInteger(s.saltA) && Number.isInteger(s.saltB) && Number.isInteger(s.concB) && Number.isInteger(s.concA * 10));
        return {
            text: [
                `${p}さんは、理科クラブの活動で、こさのちがう2しゅるいの食塩水を使った実験をしました。食塩水のこさ（%）は、食塩水全体の重さに対する、とけている食塩の重さの割合を、百分率で表したものです。食塩水の重さにこさをかけると、とけている食塩の重さをもとめることができます。`,
                `実験の前、容器Aには、こさが${v.a}%の食塩水が${v.x}g入っていました。容器Bには、こさが${v.b}%の食塩水が${v.y}g入っていました。`,
                `【そうさ1】はじめに、${p}さんは、容器Aから食塩水を${v.z}gだけくみ出して、それを容器Bに入れ、ガラスぼうでよくかきまぜました。食塩水は、どこをとってもこさが同じなので、くみ出した${v.z}gの食塩水のこさは、容器Aの食塩水のこさと同じです。`,
                `【そうさ2】次に、${p}さんは、よくかきまぜたあとの容器Bから、食塩水を${v.z}gだけくみ出して、それを容器Aにもどし、よくかきまぜました。これで、容器Aと容器Bに入っている食塩水の重さは、どちらも実験の前と同じ重さにもどりました。けれども、とけている食塩の重さは、どちらの容器も、実験の前とは変わっています。`,
                `2つの容器の食塩水をやりとりしても、2つの容器にとけている食塩の重さの合計は、実験の前と変わりません。`,
                '食塩水をくみ出すと、くみ出した食塩水にふくまれている食塩も、いっしょに移動することに注意しましょう。',
            ],
            questions: [
                q('実験の前、容器Aの食塩水にとけていた食塩の重さは何gですか。', v.saltA, 'g', [v.saltB, v.saltA + v.saltB, v.a]),
                q('そうさ1のあと、容器Bの食塩水のこさは何%になりましたか。', v.concB, '%', [(v.a + v.b) / 2, v.b + 1, v.a - 1]),
                q('そうさ2のあと、容器Aの食塩水のこさは何%になりましたか。', v.concA, '%', [v.concB, (v.a + v.concB) / 2, v.a - 1], { step: Number.isInteger(v.concA) ? 1 : 0.5 }),
            ],
        };
    },
]);

const baibai = defineTopic('g6-baibai', '売買損益（値引きと売れ残り）', [
    (r) => {
        const p = r.pick(names);
        const v = until(r, () => {
            const [cost, up, off] = [r.int(2, 8) * 100, r.pick([20, 25, 30, 40, 50]), r.pick([10, 20, 30])];
            const n = r.int(2, 6) * 60;
            const [[a1, b1], [a2, b2]] = [r.pick([[1, 2], [3, 5], [2, 3]]), r.pick([[1, 2], [2, 3], [3, 4]])];
            const list = (cost * (100 + up)) / 100;
            const sale = (list * (100 - off)) / 100;
            const n1 = (n * a1) / b1;
            const n2 = ((n - n1) * a2) / b2;
            const n3 = n - n1 - n2;
            const last = cost / 2;
            const twoDays = list * n1 + sale * n2;
            return { cost, up, off, n, a1, b1, a2, b2, list, sale, n1, n2, n3, last, twoDays, profit: twoDays + last * n3 - cost * n };
        }, x => [x.list, x.sale, x.n1, x.n2].every(Number.isInteger) && x.profit > 0 && x.n3 > 0 && x.sale > x.cost);
        return {
            text: [
                `${p}さんの家は、駅前の商店街でパン屋さんを開いています。秋のお祭りの日に、お店では、とくべつな「くりのタルト」を売ることにしました。タルトは、近くのケーキ工場に注文して作ってもらうもので、1個あたり${v.cost}円で仕入れます。このように、品物を仕入れるときのねだんを「原価」といいます。お店では、このタルトを全部で${v.n}個仕入れました。`,
                `お店では、原価の${v.up}%にあたる利益を見こんで、タルトの定価を決めました。つまり、定価は、原価の${100 + v.up}%にあたる金額です。`,
                `お祭りの1日目は、定価のままで売り、仕入れた個数全体の${v.a1}/${v.b1}が売れました。`,
                `お祭りの2日目は、少しでも多く売るために、定価の${v.off}%引きのねだんで売りました。すると、1日目に売れ残っていた個数の${v.a2}/${v.b2}が売れました。`,
                `お祭りの3日目は、最終日だったので、まだ売れ残っているタルトを、思いきって原価の半分のねだんで売りました。すると、売れ残っていたタルトは、1個残らず売り切れました。`,
                `お店の「利益」は、3日間の売り上げの合計から、タルト${v.n}個を仕入れるのにかかった金額をひいてもとめます。`,
                'ねだんを下げると、1個あたりの利益は少なくなりますが、売れ残りをへらすことができます。売れ残った品物は、仕入れにかかったお金がそのまま損になってしまうので、お店では、売れゆきを見ながら、いつ、どれくらいねだんを下げるかを決めています。原価より安いねだんで売った分は、1個売るごとに損が出ることにも注意しましょう。',
            ],
            questions: [
                q('タルト1個の定価は何円ですか。', v.list, '円', [v.cost + v.up, v.cost + v.up * 10, v.sale], { step: 10 }),
                q('1日目と2日目の売り上げの合計は何円ですか。', v.twoDays, '円', [v.list * (v.n1 + v.n2), v.list * v.n1, v.twoDays + v.last * v.n3], { step: 100 }),
                q('3日間でタルトを全部売り終わったとき、お店の利益は全部で何円でしたか。', v.profit, '円', [v.twoDays - v.cost * v.n > 0 ? v.twoDays - v.cost * v.n : v.profit + 1000, v.profit + v.cost * v.n3, (v.list - v.cost) * v.n], { step: 100 }),
            ],
        };
    },
]);

const hiYaritori = defineTopic('g6-hi', '比とお金のやりとり', [
    (r) => {
        const [p, f] = r.pickN(names, 2);
        // はじめの比 a:b、同じねだんの本を買ったあとの比 c:d、はじめの金額は本のねだんの k 倍 × (a, b)
        const [a, b, c, d, kNum, kDen] = r.pick([[5, 3, 3, 1, 1, 2], [4, 3, 3, 2, 1, 1], [7, 5, 3, 2, 1, 1], [3, 2, 5, 3, 2, 1], [5, 4, 4, 3, 1, 1], [7, 4, 2, 1, 1, 1]]);
        const book = r.int(3, 9) * 200;
        const unit = (book * kNum) / kDen;
        const [older, younger] = [a * unit, b * unit];
        return {
            text: [
                `${p}さんと妹の${f}さんは、毎月のおこづかいを少しずつためて、それぞれ自分のちょ金箱に入れています。ある日、2人がちょ金箱を開けて、中のお金を数えてみたところ、${p}さんのちょ金と${f}さんのちょ金の金額の比は、${a}:${b}でした。`,
                `2人は、そのお金を持って、いっしょに駅前の本屋さんへ出かけました。そして、2人とも、同じシリーズの図かんを1さつずつ買いました。2人が買った図かんは、どちらも1さつ${book}円です。図かんを買ったあと、2人の残りのお金をくらべてみると、${p}さんの残りのお金と${f}さんの残りのお金の比は、${c}:${d}になっていました。`,
                `2人が同じ金額ずつお金を使ったとき、2人の持っているお金の差は、使う前と変わりません。このことに注目して、比の1にあたる金額がいくらなのかを考えると、2人のはじめのちょ金の金額をもとめることができます。図かんを買う前と買ったあとで、2人の金額の差が同じになるように、比をそろえて考えてみましょう。`,
                `家に帰ってから、${p}さんは、「わたしのほうがたくさん残っているから、少し分けてあげるね」と言って、自分の残りのお金の中からいくらかを${f}さんにわたしました。すると、2人の持っているお金は、ちょうど同じ金額になりました。お母さんは、そのようすを見て、「なかよく分けられてえらいね」と2人をほめてくれました。`,
            ],
            questions: [
                q(`はじめに${p}さんのちょ金箱に入っていたお金は何円ですか。`, older, '円', [younger, older - book, older + book], { step: 100 }),
                q(`図かんを買ったあと、${f}さんの手元に残ったお金は何円ですか。`, younger - book, '円', [older - book, younger, book], { step: 100 }),
                q(`${p}さんが${f}さんにわたしたお金は何円ですか。`, (older - younger) / 2, '円', [older - younger, (older + younger) / 2 - book, (older - younger) / 2 + 100], { step: 50 }),
            ],
        };
    },
]);

const ryoukin = defineTopic('g6-ryoukin', '段階料金', [
    (r) => {
        const p = r.pick(names);
        const [base, p1, p2, p3] = [r.int(8, 14) * 100, r.int(11, 15) * 10, r.int(17, 22) * 10, r.int(25, 32) * 10];
        const [u1, u2, u3] = [r.int(12, 19), r.int(22, 29), r.int(32, 45)];
        const fee = (u) => {
            if (u <= 10) return base;
            if (u <= 20) return base + (u - 10) * p1;
            if (u <= 30) return base + 10 * p1 + (u - 20) * p2;
            return base + 10 * p1 + 10 * p2 + (u - 30) * p3;
        };
        return {
            text: [
                `${p}さんは、社会科の学習で、自分の住んでいる町の水道料金のしくみについて調べました。この町では、家庭で1か月に使った水の量（使用量）によって、その月の水道料金が決まります。使用量は、「立方メートル（m³）」という単位ではかり、1m³にみたないはんぱな量は切りすてて、整数で表します。`,
                `水道料金は、下の表のようなきまりで計算します。まず、使用量が10m³までの月は、使った量に関係なく、「基本料金」の${base}円だけをはらいます。使用量が10m³をこえた月は、基本料金のほかに、10m³をこえた分について、1m³ごとの料金をはらいます。この1m³ごとの料金は、使用量が多くなるほど高くなるように、3つの段階に分けて決められています。`,
                `たとえば、使用量が25m³の月は、基本料金に加えて、10m³をこえて20m³までの10m³分については1m³あたり${p1}円、20m³をこえた5m³分については1m³あたり${p2}円の料金をはらいます。つまり、1m³ごとの料金は、使用量の全体に同じねだんがかかるのではなく、段階ごとに分けて計算することに注意しましょう。`,
                `このように、たくさん使うほど1m³あたりの料金が高くなるしくみにしているのは、水をむだづかいしないで、大切に使ってもらうためです。${p}さんは、家にとどいた水道料金のお知らせを何か月分か集めて、表のきまりのとおりに料金が計算されているかどうかをたしかめてみることにしました。`,
            ],
            figure: table(['1か月の使用量', '料金'], [
                ['10m³まで', `基本料金 ${base}円`],
                ['10m³をこえて20m³まで', `1m³につき ${p1}円`],
                ['20m³をこえて30m³まで', `1m³につき ${p2}円`],
                ['30m³をこえた分', `1m³につき ${p3}円`],
            ], '水道料金のきまり'),
            questions: [
                q(`使用量が${u1}m³だった月の水道料金は何円ですか。`, fee(u1), '円', [base + u1 * p1, u1 * p1, fee(u1) + p1], { step: 10 }),
                q(`使用量が${u2}m³だった月の水道料金は何円ですか。`, fee(u2), '円', [base + (u2 - 10) * p2, base + u2 * p2, fee(u2) - p1 * 10], { step: 10 }),
                q(`水道料金が${fee(u3)}円だった月の使用量は何m³ですか。`, u3, 'm³', [u3 - 30, u3 + 1, Math.round(fee(u3) / p3)]),
            ],
        };
    },
]);

export default [...newton, ...kyuusui, ...yaritori, ...baibai, ...hiYaritori, ...ryoukin];
