const shigoto = defineTopic('g45-shigoto', '仕事算', [
    (r) => {
        const [a, b, c] = r.pickN(names, 3);
        // [全体の仕事量, Aの1日分, Bの1日分, Cの1日分]
        const [w, ra, rb, rc] = r.pick([[60, 4, 2, 6], [72, 6, 3, 9], [120, 5, 3, 4], [36, 3, 1, 2], [90, 6, 3, 9], [120, 6, 4, 2], [180, 9, 6, 5]]);
        const k = until(r, () => r.int(2, 9), x => (w - ra * x) % (ra + rb) === 0 && w - ra * x > 0);
        return {
            text: [
                `${a}さん、${b}さん、${c}さんの3人は、町内会にたのまれて、公民館の長いへいにペンキをぬる仕事を引き受けました。3人の仕事の速さはそれぞれちがいますが、どの人も、毎日同じ時間だけ働き、自分の速さを変えずに仕事を進めるものとします。`,
                `この仕事を1人だけで仕上げるとすると、${a}さんはちょうど${w / ra}日、${b}さんはちょうど${w / rb}日かかります。${c}さんが1人だけで仕上げるのに何日かかるかは、はじめのうちは、わかっていませんでした。`,
                `そこで、ためしに3人がいっしょに働いた場合のことを計算してみたところ、この仕事は、3人ならちょうど${w / (ra + rb + rc)}日で仕上がることがわかりました。`,
                `じっさいには、${c}さんは急な用事で来られなくなったので、まず${a}さんが1人で${k}日間働き、そのあとは${a}さんと${b}さんの2人で、残りの仕事を仕上げました。`,
            ],
            questions: [
                q(`もし、はじめから${a}さんと${b}さんの2人がいっしょに働いたとすると、この仕事は何日で仕上がりますか。`, w / (ra + rb), '日', [(w / ra + w / rb) / 2, w / ra + w / rb, w / ra - 1]),
                q(`じっさいには、${a}さんと${b}さんの2人で働いたのは何日間でしたか。`, (w - ra * k) / (ra + rb), '日間', [w / (ra + rb) - k, w / (ra + rb), (w - ra * k) / ra]),
                q(`${c}さんが1人だけでこの仕事を仕上げるとすると、何日かかりますか。`, w / rc, '日', [w / (ra + rb + rc), w / ra + w / rb, w / rc + 2]),
            ],
        };
    },
]);

const nobe = defineTopic('g45-nobe', 'のべ算', [
    (r) => {
        const v = until(r, () => {
            const [n, d, k, m] = [r.int(4, 9), r.int(8, 20), r.int(2, 6), r.int(1, 5)];
            const x = r.int(4, 12);
            return { n, d, k, m, x, left: (n * d - n * k) / (n + m), need: (n * d) / x };
        }, z => Number.isInteger(z.left) && Number.isInteger(z.need) && z.k < z.d - 2 && z.x !== z.d && z.need !== z.n);
        return {
            text: [
                `ある農家では、広い畑のじゃがいもを全部ほり出す仕事を、アルバイトの人たちにたのむことにしました。アルバイトの人は、だれもが同じ速さで働き、1日に働く時間も全員同じだとします。`,
                `農家の人の計算では、この仕事は、${v.n}人で働くと、ちょうど${v.d}日で終わります。このように、「何人で何日」という形で表された仕事の量は、人数と日数をかけ合わせて、「のべ何人分」というように考えると、わかりやすくなります。たとえば、3人で4日かかる仕事は、のべ12人分の仕事で、1人なら12日、6人なら2日で終わります。`,
                `じっさいには、はじめの${v.k}日間は予定どおり${v.n}人で働きましたが、台風が近づいてきたので、${v.k + 1}日目からはアルバイトの人を${v.m}人ふやして、残りの仕事を終わらせました。`,
                'アルバイトの人たちは、とちゅうで休んだり交代したりすることなく、決められた日は毎日同じように働きます。',
            ],
            questions: [
                q('この仕事を1人だけですると、何日かかりますか。', v.n * v.d, '日', [v.n + v.d, v.d, v.n * v.d - v.n]),
                q('人数をふやしてから、残りの仕事が終わるまでに、何日かかりましたか。', v.left, '日', [v.d - v.k, (v.n * v.d) / (v.n + v.m), v.left + v.k]),
                q(`もし、はじめからちょうど${v.x}日でこの仕事を終わらせるとしたら、何人で働けばよかったですか。`, v.need, '人', [v.n + v.m, v.need + 1, v.need - 1]),
            ],
        };
    },
]);

const saatsume = defineTopic('g45-saatsume', '差集め算', [
    (r) => {
        const p = r.pick(names);
        const v = until(r, () => {
            const [a, up, n] = [r.int(8, 15) * 10, r.int(2, 6) * 10, r.int(8, 20)];
            return { a, b: a + up, n, money: a * n, short: up * n };
        }, x => x.money % x.b !== 0);
        return {
            text: [
                `${p}さんは、お母さんにたのまれて、おばあさんの家に持っていくくだものを買いに、八百屋さんへ行きました。お母さんからは、「1個${v.a}円のりんごを、この数だけ買ってきてね」と言われ、おつりが出ないように、りんごの代金とぴったり同じ金額のお金をあずかりました。${p}さんは、それ以外のお金は持っていません。`,
                `ところが、八百屋さんに着いてみると、りんごはちょうど売り切れてしまっていました。お店の人にたずねると、「今日は、なしがおいしいよ。1個${v.b}円だよ」とすすめてくれました。`,
                `そこで${p}さんは、たのまれたりんごと同じ個数のなしを買おうと考えました。しかし、計算してみると、あずかったお金では${v.short}円足りないことがわかりました。${p}さんは、しかたなく、あずかったお金で買えるだけの個数のなしを買って帰ることにしました。`,
            ],
            questions: [
                q('お母さんにたのまれたりんごの個数は、何個ですか。', v.n, '個', [v.short / v.a, Math.floor(v.money / v.b), v.n + 2]),
                q(`${p}さんがお母さんからあずかったお金は、何円ですか。`, v.money, '円', [v.b * v.n, v.money - v.short, v.money + v.short], { step: 10 }),
                q('なしを買えるだけ買ったとき、手元に残ったお金は何円ですか。', v.money % v.b, '円', [v.short, v.b - (v.money % v.b), v.money - v.b * (Math.floor(v.money / v.b) - 1)], { step: 10 }),
            ],
        };
    },
]);

const benshou = defineTopic('g45-benshou', 'つるかめ算（べんしょう算）', [
    (r) => {
        const p = r.pick(names);
        const v = until(r, () => {
            const [a, b, n] = [r.int(3, 8) * 10, r.int(10, 30) * 10, r.int(20, 50) * 10];
            const x = r.int(2, 9);
            return { a, b, n, x, full: a * n, got: a * (n - x) - b * x };
        }, z => z.got - (z.a + z.b) * z.x > 0);
        return {
            text: [
                `${p}さんのお兄さんは、引っこしセンターでアルバイトをしています。ある日の仕事は、ガラスのコップ${v.n}個を、倉庫からお店まで、1個ずつていねいに運ぶことでした。`,
                `この仕事では、コップを1個、割らずにお店まで運ぶごとに、${v.a}円の運び賃がもらえます。ところが、運ぶとちゅうでコップを割ってしまった場合は、その1個分の運び賃がもらえないだけでなく、べんしょう金として、1個につき${v.b}円をはらわなければならないきまりになっています。べんしょう金は、もらえるはずの運び賃の合計からひかれます。`,
                `お兄さんは、コップ${v.n}個を全部運び終わりましたが、とちゅうで何個かを割ってしまいました。そのため、仕事が終わってからじっさいに受け取ったお金は、${v.got}円でした。`,
                'コップを1個割ると、1個も割らなかった場合にくらべて、受け取るお金は、運び賃とべんしょう金を合わせた金額の分だけ少なくなります。',
            ],
            questions: [
                q(`もし、コップを1個も割らずに${v.n}個全部を運んだとすると、受け取るお金は何円でしたか。`, v.full, '円', [v.got + v.b, v.full - v.b, v.got + v.a * v.x], { step: 100 }),
                q('お兄さんが割ってしまったコップは何個ですか。', v.x, '個', [(v.full - v.got) / v.a, (v.full - v.got) / v.b, v.x + 1]),
                q('もし、割ったコップの数がじっさいの2倍だったとすると、受け取るお金は何円でしたか。', v.got - (v.a + v.b) * v.x, '円', [v.got - v.b * v.x, v.got / 2, v.got - v.a * v.x], { step: 10 }),
            ],
        };
    },
]);

const nenrei = defineTopic('g45-nenrei', '年令算', [
    (r) => {
        const [p, f] = r.pickN(names, 2);
        const v = until(r, () => {
            const [c1, gap] = [r.int(9, 12), r.int(2, 4)];
            const c2 = c1 - gap;
            const father = r.int(36, 45);
            const mother = father - r.int(1, 4);
            const z = r.int(2, 5);
            return {
                c1, c2, father, mother, z,
                y1: father - c1 - c2,
                y2: (father + mother - 3 * (c1 + c2)) / 4,
                times: (father - z) / (c1 - z),
            };
        }, x => x.y1 >= 8 && Number.isInteger(x.y2) && x.y2 >= 2 && Number.isInteger(x.times) && x.y1 !== x.y2);
        return {
            text: [
                `${p}さんの家族は、お父さん、お母さん、${p}さん、弟の${f}さんの4人です。今年のたん生日をむかえたあとの年令は、お父さんが${v.father}才、お母さんが${v.mother}才、${p}さんが${v.c1}才、${f}さんが${v.c2}才です。4人とも、1年たつごとに、1才ずつ年をとります。`,
                `ある日の夕食のとき、お父さんが、「2人とも大きくなったなあ。そのうち、${p}と${f}の年令をたした数が、お父さんの年令と同じになる年が来るんだよ」と言いました。`,
                `それを聞いた${p}さんは、家族の年令について、ほかにも調べてみたくなりました。そこで、「お父さんとお母さんの年令の和が、子ども2人の年令の和のちょうど3倍になるのはいつか」や、「${v.z}年前、お父さんの年令は、自分の年令の何倍だったか」を、計算でもとめてみることにしました。`,
                '何年たっても、2人の人の年令の差は変わりません。けれども、年令の和は、人数が多いほど、1年ごとに大きくふえていきます。',
            ],
            questions: [
                q(`${p}さんと${f}さんの年令の和が、お父さんの年令と同じになるのは、今から何年後ですか。`, v.y1, '年後', [v.father - v.c1, (v.father - v.c1 - v.c2) / 2, v.y1 + v.c2]),
                q('お父さんとお母さんの年令の和が、子ども2人の年令の和のちょうど3倍になるのは、今から何年後ですか。', v.y2, '年後', [(v.father + v.mother - 3 * (v.c1 + v.c2)) / 2, v.y2 * 4, v.y2 + 2]),
                q(`${v.z}年前、お父さんの年令は、${p}さんの年令の何倍でしたか。`, v.times, '倍', [v.times + 1, v.times - 1, Math.round(v.father / v.c1)]),
            ],
        };
    },
]);

const baai = defineTopic('g45-baai', '場合の数', [
    (r) => {
        const p = r.pick(names);
        const [a, b, c] = [r.int(3, 5), r.int(4, 6), r.int(2, 4)];
        const pairs = (b * (b - 1)) / 2;
        const main = ['カレーライス', 'スパゲッティ', 'オムライス', 'ハンバーグ', 'ピザ'].slice(0, a);
        const side = ['サラダ', 'スープ', 'ポテト', 'からあげ', 'コロッケ', 'グラタン'].slice(0, b);
        const sweet = ['プリン', 'アイス', 'ゼリー', 'ケーキ'].slice(0, c);
        return {
            text: [
                `${p}さんは、家族といっしょに、新しくできたレストランへ食事に出かけました。このレストランでは、下の表のメニューの中から、自分のすきなものを組み合わせて注文することができます。`,
                `「メイン」は${a}しゅるい、「サイド」は${b}しゅるい、「デザート」は${c}しゅるいあります。どの料理も、同じものを2つ注文することはしないものとします。また、選ぶ順番がちがっていても、選んだ料理の組み合わせが同じであれば、同じ注文として数えます。`,
                `${p}さんは、メニューを見ながら、「メインとサイドを1つずつ選ぶだけでも、ずいぶんたくさんの選び方があるなあ」と思いました。そこで、料理が来るのを待っている間に、注文のしかたが全部で何通りあるのかを、いろいろな場合について数えてみることにしました。`,
                '数えるときには、表や図にかいて順序よく整理すると、数えまちがいや、数えわすれをふせぐことができます。',
            ],
            figure: table(['', '料理'], [['メイン', main.join('、')], ['サイド', side.join('、')], ['デザート', sweet.join('、')]], 'レストランのメニュー'),
            questions: [
                q('メインを1つ、サイドを1つ選ぶとき、注文のしかたは全部で何通りありますか。', a * b, '通り', [a + b, a * b * c, a * (b - 1)]),
                q('メインを1つ、サイドを1つ選び、さらに、デザートを「1つ選ぶ」か「たのまない」かのどちらかにするとき、注文のしかたは全部で何通りありますか。', a * b * (c + 1), '通り', [a * b * c, a * b + c, a * b + c + 1]),
                q('メインを1つと、サイドをちがうものから2つ選ぶとき、注文のしかたは全部で何通りありますか。', a * pairs, '通り', [a * b * (b - 1), a * b * 2, a + pairs]),
            ],
        };
    },
]);

const heikin = defineTopic('g45-heikin', '平均算', [
    (r) => {
        const p = r.pick(names);
        const v = until(r, () => {
            const [m, f] = [r.int(12, 18), r.int(12, 18)];
            const [am, af] = [r.int(60, 80), r.int(60, 80)];
            const total = m * am + f * af;
            const avg = total / (m + f);
            const up = r.pick([-0.5, 0.5, 1]);
            return { m, f, am, af, total, avg, up, late: (avg + up) * (m + f + 1) - total };
        }, x => x.m !== x.f && x.am !== x.af && Number.isInteger(x.avg) && Number.isInteger(x.late) && x.late <= 100 && x.late >= 30);
        return {
            text: [
                `${r.pick(schools)}小学校の5年2組で、算数のテストがありました。テストは100点満点です。テストの日、${p}さんはかぜをひいて学校を休んでしまったので、この日にテストを受けたのは、${p}さんをのぞいた、男子${v.m}人と女子${v.f}人でした。`,
                `先生が採点をして、男子と女子に分けて平均点を計算したところ、男子${v.m}人の平均点は${v.am}点、女子${v.f}人の平均点は${v.af}点でした。平均点は、全員の点数の合計を、人数でわってもとめます。ですから、平均点と人数がわかれば、点数の合計をもとめることができます。`,
                `次の週、かぜがなおった${p}さんは、放課後に、同じテストを1人で受けました。先生が、${p}さんの点数も入れて、クラス全員の平均点を計算し直したところ、平均点は${v.avg + v.up}点になりました。`,
                'なお、男子の人数と女子の人数がちがうときは、男子の平均点と女子の平均点をたして2でわっても、全員の平均点にはならないので、注意が必要です。',
            ],
            questions: [
                q(`テストの日に受けた男子${v.m}人の点数の合計は、何点ですか。`, v.m * v.am, '点', [v.m + v.am, v.f * v.af, v.m * v.am + v.am], { step: 10 }),
                q(`テストの日に受けた${v.m + v.f}人全員の平均点は、何点ですか。`, v.avg, '点', [(v.am + v.af) / 2, v.avg + 2]),
                q(`${p}さんの点数は何点でしたか。`, v.late, '点', [v.avg + v.up, v.late - (v.m + v.f), v.late + 5]),
            ],
        };
    },
]);

export default [...shigoto, ...nobe, ...saatsume, ...benshou, ...nenrei, ...baai, ...heikin];
